/**
 * Looks up coordinates for a birth city string.
 * Tries: exact normalized key, then strips US state abbreviations.
 * Returns { lat, lon } or null if not found.
 */
function lookupCity(raw) {
  if (!raw) return null;

  // Normalize: lowercase, collapse whitespace, remove trailing commas
  const norm = raw.toLowerCase().trim().replace(/,/g, ' ').replace(/\s+/g, ' ').trim();

  if (CITIES[norm]) return CITIES[norm];

  // Try stripping a trailing two-letter state/country code: "rochester ny" → "rochester"
  const withoutCode = norm.replace(/\s+[a-z]{2}$/, '').trim();
  if (withoutCode !== norm && CITIES[withoutCode]) return CITIES[withoutCode];

  // Try stripping everything after the first comma equivalent (already removed above)
  // Try first word only as last resort for very short city names
  const firstWord = norm.split(' ')[0];
  if (firstWord.length > 4 && CITIES[firstWord]) return CITIES[firstWord];

  return null;
}

